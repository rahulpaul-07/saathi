"""Machine-translate the interface text (English -> X, local IndicTrans2, no network),
back-translate it, and write src/saathi/chrome_data.py and the drift report in eval/results/.

  uv run --no-sync python scripts/gen_chrome.py

Texts already marked "reviewed" in chrome_data.py are kept as they are. Everything else is
regenerated and marked "pending" until a speaker checks it. The back-translation report flags
strings whose round trip lost many of the source words; it is a list to read, not a quality score.
Needs the en-indic and indic-en models (downloaded once from HF); uses no Gnani calls.
"""

import json
import sys
from pathlib import Path

from saathi.chrome import ENGLISH, SOURCE, word_overlap
from saathi.chrome_data import TRANSLATED
from saathi.languages import LANGUAGES
from saathi.translate import RoutingTranslator

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "src" / "saathi" / "chrome_data.py"
REPORT = ROOT / "eval" / "results" / "chrome_backtranslation.json"
DRIFT_BELOW = 0.5


def literal(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def write_data(table: dict[str, dict[str, tuple[str, str]]]) -> None:
    lines = [
        '"""Generated by scripts/gen_chrome.py. Do not edit by hand."""',
        "",
        "from saathi.quickreplies import ReviewStatus",
        "",
        "TRANSLATED: dict[str, dict[str, tuple[str, ReviewStatus]]] = {",
    ]
    for code, strings in table.items():
        lines.append(f'    "{code}": {{')
        for key, (text, status) in strings.items():
            lines.append(f'        "{key}": ({literal(text)}, "{status}"),')
        lines.append("    },")
    lines.append("}")
    DATA.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    translator = RoutingTranslator()
    translator.load(("en-indic", "indic-en"))
    table: dict[str, dict[str, tuple[str, str]]] = {}
    rows: list[dict[str, object]] = []
    for code in LANGUAGES:
        if code == SOURCE:
            continue
        table[code] = {}
        for key, english in ENGLISH.items():
            kept = TRANSLATED.get(code, {}).get(key)
            if kept is not None and kept[1] == "reviewed":
                table[code][key] = kept
                continue
            text = translator.translate(english, SOURCE, code)
            back = translator.translate(text, code, SOURCE)
            score = round(word_overlap(english, back), 2)
            table[code][key] = (text, "pending")
            rows.append({"lang": code, "key": key, "back": back, "overlap": score,
                         "flagged": score < DRIFT_BELOW})
    write_data(table)
    flagged = [r for r in rows if r["flagged"]]
    REPORT.write_text(
        json.dumps({"drift_below": DRIFT_BELOW, "strings": len(rows), "flagged": len(flagged),
                    "rows": rows}, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8",
    )
    print(f"{len(rows)} strings, {len(flagged)} flagged for drift (overlap < {DRIFT_BELOW})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
